package me.naook1.nereusclasses;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import org.bukkit.Color;
import org.bukkit.Material;
import org.bukkit.NamespacedKey;
import org.bukkit.attribute.Attribute;
import org.bukkit.attribute.AttributeModifier;
import org.bukkit.inventory.EquipmentSlotGroup;
import org.bukkit.inventory.ItemFlag;
import org.bukkit.inventory.ItemStack;
import org.bukkit.inventory.meta.ItemMeta;
import org.bukkit.inventory.meta.LeatherArmorMeta;
import org.bukkit.persistence.PersistentDataType;

/** item registry (generated by the asset pipeline) + item factory. */
final class Items {

    record Reg(String key, String kind, Material carrier, int cmd, String name, String cls, String color) {
    }

    private final NereusClasses plugin;
    private final Map<String, Reg> reg = new LinkedHashMap<>();
    final NamespacedKey tag;

    Items(NereusClasses plugin) {
        this.plugin = plugin;
        this.tag = new NamespacedKey(plugin, "item");
        try (InputStream in = plugin.getResource("registry.json")) {
            if (in != null) {
                JsonArray a = JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonArray();
                for (JsonElement e : a) {
                    JsonObject o = e.getAsJsonObject();
                    Material m = Material.matchMaterial(o.get("carrier").getAsString());
                    if (m == null) {
                        continue;
                    }
                    String color = o.has("color") ? o.get("color").getAsString() : "";
                    reg.put(o.get("key").getAsString(), new Reg(o.get("key").getAsString(), o.get("kind").getAsString(), m,
                            o.get("cmd").getAsInt(), o.get("name").getAsString(), o.get("cls").getAsString(), color));
                }
            }
        } catch (Exception ex) {
            plugin.getLogger().warning("registry.json: " + ex);
        }
    }

    Reg get(String key) {
        return reg.get(key);
    }

    List<Reg> kind(String kind) {
        List<Reg> out = new ArrayList<>();
        for (Reg r : reg.values()) {
            if (r.kind().equals(kind)) {
                out.add(r);
            }
        }
        return out;
    }

    int size() {
        return reg.size();
    }

    /** plain model carrier (VFX frames, icons). */
    ItemStack frame(String key) {
        Reg r = reg.get(key);
        if (r == null) {
            return null;
        }
        ItemStack it = new ItemStack(r.carrier());
        ItemMeta m = it.getItemMeta();
        if (r.cmd() > 0) {
            m.setCustomModelData(r.cmd());
        }
        m.getPersistentDataContainer().set(tag, PersistentDataType.STRING, key);
        it.setItemMeta(m);
        return it;
    }

    /** real usable item (weapon / armor / head). */
    ItemStack make(String key, double damage, double speed, List<String> lore) {
        Reg r = reg.get(key);
        if (r == null) {
            return null;
        }
        ItemStack it = new ItemStack(r.carrier());
        ItemMeta m = it.getItemMeta();
        if (r.cmd() > 0) {
            m.setCustomModelData(r.cmd());
        }
        m.setDisplayName(NereusClasses.color(r.name()));
        if (lore != null && !lore.isEmpty()) {
            List<String> l = new ArrayList<>();
            for (String s : lore) {
                l.add(NereusClasses.color(s));
            }
            m.setLore(l);
        }
        m.setUnbreakable(true);
        m.addItemFlags(ItemFlag.HIDE_UNBREAKABLE, ItemFlag.HIDE_ATTRIBUTES, ItemFlag.HIDE_DYE);
        if (m instanceof LeatherArmorMeta lm && !r.color().isEmpty()) {
            String[] c = r.color().split(",");
            lm.setColor(Color.fromRGB(Integer.parseInt(c[0].trim()), Integer.parseInt(c[1].trim()), Integer.parseInt(c[2].trim())));
        }
        if (r.kind().equals("weapon") && damage > 0) {
            m.addAttributeModifier(Attribute.GENERIC_ATTACK_DAMAGE,
                    new AttributeModifier(new NamespacedKey(plugin, "dmg_" + key), damage - 1.0, AttributeModifier.Operation.ADD_NUMBER, EquipmentSlotGroup.MAINHAND));
            m.addAttributeModifier(Attribute.GENERIC_ATTACK_SPEED,
                    new AttributeModifier(new NamespacedKey(plugin, "spd_" + key), speed - 4.0, AttributeModifier.Operation.ADD_NUMBER, EquipmentSlotGroup.MAINHAND));
        }
        m.getPersistentDataContainer().set(tag, PersistentDataType.STRING, key);
        it.setItemMeta(m);
        return it;
    }

    String keyOf(ItemStack it) {
        if (it == null || it.getType().isAir() || !it.hasItemMeta()) {
            return null;
        }
        return it.getItemMeta().getPersistentDataContainer().get(tag, PersistentDataType.STRING);
    }

    static Material mat(String s) {
        return Material.matchMaterial(s.toUpperCase(Locale.ROOT));
    }
}
